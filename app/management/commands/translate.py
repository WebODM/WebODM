import os
import json
import glob
from django.conf import settings
from django.core.management.base import BaseCommand, CommandError
from django.core.management import call_command

from app.scripts.extract_odx_strings import extract_odx_strings
from app.scripts.extract_plugin_manifest_strings import extract_plugin_manifest_strings

root = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", ".."))

class Command(BaseCommand):
    requires_system_checks = []

    def add_arguments(self, parser):
        parser.add_argument("action", type=str, choices=['extract', 'build', 'langs'])
        parser.add_argument("--safe", action='store_true', required=False, help="Skip invalid languages")
        parser.add_argument("--skip-extract", action='store_true', required=False, help="Skip extraction of dependencies strings")
        parser.add_argument("--plugin", type=str, required=False, help="Extract or build the translations of a plugin (name or path) into its own locale folder")
        parser.add_argument("--output", type=str, required=False, help="Save the output of langs to this file")
        super(Command, self).add_arguments(parser)

    def handle(self, **options):
        if options.get('action') == 'langs':
            from app.templatetags.settings import language_list
            out = json.dumps(language_list())
            if options.get('output'):
                with open(options['output'], 'w', encoding='utf-8') as f:
                    f.write(out)
            else:
                self.stdout.write(out)
            return

        with open(os.path.join(root, "LOCALES")) as f:
            locales = f.read().strip().split(" ")

        if options.get('plugin'):
            plugin_path = options['plugin']
            if not os.path.isdir(plugin_path):
                from app.plugins.functions import get_plugin_by_name
                plugin = get_plugin_by_name(plugin_path, only_active=False)
                if plugin is None:
                    raise CommandError("Plugin not found: %s" % plugin_path)
                plugin_path = plugin.get_path()
            plugin_path = os.path.abspath(plugin_path)
            if not os.path.isfile(os.path.join(plugin_path, "manifest.json")):
                raise CommandError("Not a plugin (missing manifest.json): %s" % plugin_path)

            locale_dir = os.path.join(plugin_path, "locale")
            ignore = ['--ignore=build', '--ignore=node_modules', '--ignore=locale']
            cwd = os.getcwd()
            locale_paths = settings.LOCALE_PATHS
            settings.LOCALE_PATHS = [locale_dir]
            os.chdir(plugin_path)

            try:
                if options.get('action') == 'extract':
                    print("Extracting .po files for %s" % plugin_path)
                    locale_params = ["--locale=%s" % l for l in locales]
                    os.makedirs(locale_dir, exist_ok=True)

                    with open("manifest.json") as f:
                        description = json.load(f).get("description")
                    manifest_strings = os.path.join(plugin_path, "manifest_strings_autogenerated.py")
                    if description:
                        with open(manifest_strings, "w") as f:
                            f.write("from django.utils.translation import gettext as _\n")
                            f.write("_(%s)\n" % json.dumps(description))

                    try:
                        call_command('makemessages', *locale_params, *ignore)
                        call_command('makemessages_djangojs', *locale_params, '-d=djangojs', '--extension=jsx', '--extension=js', *ignore, '--language=Python')
                    finally:
                        if os.path.exists(manifest_strings):
                            os.remove(manifest_strings)
                else:
                    print("Building .po files into .mo for %s" % plugin_path)
                    call_command('compilemessages', *ignore[:2])
            finally:
                os.chdir(cwd)
                settings.LOCALE_PATHS = locale_paths
            return

        if options.get('action') == 'extract':
            print("Extracting .po files from Django/React")
            locale_params = ["--locale=%s" % l for l in locales]
            
            locale_dir = os.path.join(root, "locale")
            if not os.path.exists(locale_dir):
                os.mkdir(locale_dir)

            if not options.get('skip_extract'):            
                extract_odx_strings(
                    "https://raw.githubusercontent.com/WebODM/ODX/master/modules/config.py",
                    os.path.join(root, "app", "static", "app", "js", "translations", "odm_autogenerated.js")
                )
                extract_plugin_manifest_strings(
                    os.path.join(root, "coreplugins"), 
                    os.path.join(root, "app", "translations", "plugin_manifest_autogenerated.py")
                )

            plugins_ignore = ['--ignore=app/media*']
            for d in glob.glob(os.path.join(root, "coreplugins", "*", "locale")):
                plugin_dir = os.path.relpath(os.path.dirname(d), root)
                print("Skipping %s (has its own locale folder)" % plugin_dir)
                plugins_ignore.append("--ignore=%s" % plugin_dir)

            call_command('makemessages', '--keep-pot', *locale_params, '--ignore=build', '--ignore=app/templates/app/registration/*', '--ignore=venv/*', *plugins_ignore)
            call_command('makemessages_djangojs', '--keep-pot', *locale_params, '-d=djangojs', '--extension=jsx', '--extension=js', '--ignore=build', '--ignore=app/static/app/js/vendor', '--ignore=app/static/app/bundles', '--ignore=node_modules', '--ignore=venv/*', '--ignore=slate/*', '--ignore=nodeodm/*', *plugins_ignore, '--language=Python')

        elif options.get('action') == 'build':
            ignore = ['--ignore=build', '--ignore=node_modules', '--ignore=venv', '--ignore=slate', '--ignore=nodeodm', '--ignore=app/media*']
            if options.get('safe'):
                for l in locales:
                    print("Building %s .po files into .mo" % l)
                    call_command('compilemessages', '--locale=%s' % l, *ignore)
            else:
                print("Building .po files into .mo")
                call_command('compilemessages', *ignore)